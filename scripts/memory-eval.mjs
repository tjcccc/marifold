#!/usr/bin/env node
import { createRequire } from 'node:module';
import * as fs from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, '..');
const coreDist = path.join(repoRoot, 'packages/core/dist/index.js');

if (!fs.existsSync(coreDist)) {
  process.stderr.write(`Core build not found: ${coreDist}\n`);
  process.stderr.write('Run pnpm build before running scripts/memory-eval.mjs.\n');
  process.exit(1);
}

const {
  MarifoldRuntime,
  ensureProfileMemoryFiles,
} = require(coreDist);

if (process.argv.slice(2).includes('--help')) {
  printHelp();
  process.exit(0);
}

const args = parseArgs(process.argv.slice(2));
const provider = args.provider ?? 'ollama';
const providerType = args.providerType ?? (provider === 'anthropic' ? 'anthropic' : provider === 'ollama' ? 'ollama' : 'openai-compatible');
const model = args.model ?? 'gemma4:e4b';
const suite = args.suite ?? 'professional';
const profile = args.profile ?? `memory_eval_${randomSuffix()}`;
const keep = Boolean(args.keep);
const stopOnFail = Boolean(args.stopOnFail);
const root = args.workdir ? path.resolve(expandHome(args.workdir)) : fs.mkdtempSync(path.join(os.tmpdir(), 'marifold-memory-eval-'));
const profilesDir = path.join(root, 'profiles');
const memoriesDir = path.join(profilesDir, profile, 'memories');
const sessionsDb = path.join(root, 'sessions.db');
const configPath = path.join(root, 'config.toml');

try {
  fs.mkdirSync(root, { recursive: true });
  writeProfile(profilesDir, profile, provider, model);
  const config = buildConfig({
    provider,
    providerType,
    model,
    profile,
    profilesDir,
    sessionsDb,
    baseUrl: args.baseUrl,
    apiKeyEnv: args.apiKeyEnv,
    apiKey: args.apiKey,
    timeoutSeconds: numberArg(args.timeout, 120),
    maxOutputTokens: numberArg(args.maxOutputTokens, 512),
    maxSystemChars: numberArg(args.maxSystemChars, undefined),
    contextLimit: numberArg(args.contextLimit, 2400),
    sizeLimit: numberArg(args.sizeLimit, 50000),
    think: Boolean(args.thinking),
  });
  fs.writeFileSync(configPath, '# Generated by scripts/memory-eval.mjs\n');

  const runtime = new MarifoldRuntime({
    loadedConfig: {
      config,
      configPath,
      foundConfig: true,
    },
  });

  const sessionId = `memory-eval-${randomSuffix()}`;
  const results = [];
  try {
    for (const step of cases(suite)) {
      const beforeRows = memoryRows(memoriesDir);
      const response = await runtime.ask({
        prompt: step.prompt,
        profile,
        sessionId,
        think: Boolean(args.thinking),
      });
      const afterRows = memoryRows(memoriesDir);
      const failures = [];
      if (!response.ok) failures.push(`model request failed: ${response.error?.message ?? 'unknown error'}`);
      if (response.ok && !response.text.trim()) failures.push('visible reply was empty');
      if (step.reply) failures.push(...checkReply(step.reply, response.text ?? ''));
      failures.push(...checkMemory(afterRows, step.memory ?? []));
      failures.push(...checkForbiddenMemory(afterRows, step.forbiddenMemory ?? []));

      const result = {
        name: step.name,
        prompt: step.prompt,
        response: response.text ?? '',
        passed: failures.length === 0,
        failures,
        memoryRowsBefore: beforeRows.length,
        memoryRowsAfter: afterRows.length,
        memoryRows: afterRows,
      };
      results.push(result);
      printStep(result);
      if (stopOnFail && failures.length > 0) break;
    }
  } finally {
    runtime.close();
  }

  const passed = results.every(result => result.passed);
  if (args.jsonReport) {
    fs.writeFileSync(path.resolve(expandHome(args.jsonReport)), JSON.stringify({
      suite,
      provider,
      model,
      profile,
      workdir: root,
      passed,
      results,
    }, null, 2));
  }
  process.stdout.write(`\n${passed ? 'PASS' : 'FAIL'} ${results.filter(result => result.passed).length}/${results.length} memory eval steps\n`);
  if (keep) process.stdout.write(`Kept eval workspace: ${root}\n`);
  if (!passed) process.exitCode = 1;
} catch (error) {
  process.stderr.write(`\nFAIL: ${error instanceof Error ? error.message : String(error)}\n`);
  process.stderr.write(`Eval workspace: ${root}\n`);
  process.exitCode = 1;
} finally {
  if (!keep && !args.workdir) fs.rmSync(root, { recursive: true, force: true });
}

function smokeCases() {
  return [
    {
      name: 'save_name',
      prompt: 'Memory test: my name is Jack.',
      memory: [
        memoryCheck('user', ['jack'], 'name saved as stable user memory', { conflictKey: 'user.name', maxPriority: 0 }),
      ],
    },
    {
      name: 'save_editor',
      prompt: 'Memory test: My favorite editor is Neovim.',
      memory: [
        memoryCheck('user', ['neovim'], 'favorite editor saved as user memory', { conflictKey: 'user.favorite_editor', maxPriority: 3 }),
      ],
    },
    {
      name: 'recall_editor',
      prompt: 'Which editor do I like?',
      reply: {
        allOf: ['neovim'],
        description: 'recalls favorite editor',
      },
    },
    {
      name: 'natural_save_color',
      prompt: 'My favorite color is yellow.',
      memory: [
        memoryCheck('user', ['yellow', 'favorite', 'color'], 'favorite color saved from natural prompt', { conflictKey: 'user.favorite_color', maxPriority: 3 }),
      ],
    },
    {
      name: 'natural_update_color',
      prompt: 'Actually, my favorite color is green, not yellow.',
      memory: [
        memoryCheck('user', ['green', 'favorite', 'color'], 'favorite color correction saved', { conflictKey: 'user.favorite_color', maxPriority: 3 }),
      ],
      forbiddenMemory: [
        forbiddenMemoryCheck('user', 'yellow', 'old favorite color should not remain active', 'not yellow'),
      ],
    },
    {
      name: 'recall_color',
      prompt: 'What is my favorite color?',
      reply: {
        allOf: ['green'],
        noneOf: ['yellow'],
        description: 'recalls corrected favorite color',
      },
    },
  ];
}

function professionalCases() {
  return [
    ...smokeCases(),
    {
      name: 'save_style',
      prompt: 'Memory test: I prefer short, normal conversation replies.',
      memory: [
        memoryCheck('preferences', ['short', 'replies'], 'reply style saved as preference memory', { conflictKey: 'preferences.reply_style', maxPriority: 3 }),
      ],
    },
    {
      name: 'save_meeting',
      prompt: 'Memory test: I have a project meeting tomorrow at 3 p.m.',
      memory: [
        memoryCheck('auto_short', ['project', 'meeting', 'tomorrow', '3'], 'project meeting saved as short-term memory', { conflictKey: 'auto_short.project_meeting_time', maxPriority: 3 }),
      ],
    },
    {
      name: 'recall_meeting',
      prompt: 'What time is the project meeting?',
      reply: {
        allOf: ['3', 'tomorrow'],
        description: 'recalls project meeting time and date word',
      },
    },
    {
      name: 'forget_color',
      prompt: 'Please forget my favorite color.',
      forbiddenMemory: [
        forbiddenMemoryCheck('user', 'green', 'favorite color should no longer be active'),
      ],
    },
    {
      name: 'recall_forgotten_color',
      prompt: 'What is my favorite color?',
      reply: {
        anyOf: ['do not know', "don't know", 'not sure', 'no active', 'forgot', 'no record', 'you asked me to forget'],
        noneOf: ['green', 'yellow'],
        description: 'does not recall soft-forgotten favorite color',
      },
    },
  ];
}

function cases(name) {
  if (name === 'smoke') return smokeCases();
  if (name === 'professional') return professionalCases();
  throw new Error(`Unknown suite ${name}. Use --suite smoke or --suite professional.`);
}

function memoryCheck(kind, allOf, description, options = {}) {
  return {
    kind,
    allOf,
    description,
    status: options.status ?? 'active',
    maxPriority: options.maxPriority,
    minConfidence: options.minConfidence,
    conflictKey: options.conflictKey,
  };
}

function forbiddenMemoryCheck(kind, pattern, description, unless) {
  return {
    kind,
    pattern,
    description,
    status: 'active',
    unless,
  };
}

function checkReply(check, response) {
  const failures = [];
  const text = response.toLowerCase();
  if (check.anyOf && !check.anyOf.some(pattern => text.includes(pattern.toLowerCase()))) {
    failures.push(`reply did not match any expected phrase for ${check.description}: ${check.anyOf.join(', ')}`);
  }
  for (const pattern of check.allOf ?? []) {
    if (!text.includes(pattern.toLowerCase())) failures.push(`reply missing expected phrase for ${check.description}: ${pattern}`);
  }
  for (const pattern of check.noneOf ?? []) {
    if (text.includes(pattern.toLowerCase())) failures.push(`reply included forbidden phrase for ${check.description}: ${pattern}`);
  }
  return failures;
}

function checkMemory(rows, checks) {
  const failures = [];
  for (const check of checks) {
    const matches = rows.filter(row => {
      if (check.kind && row.kind !== check.kind) return false;
      if (check.status && (row.status ?? 'active') !== check.status) return false;
      if (check.conflictKey !== undefined && row.conflict_key !== check.conflictKey) return false;
      const text = String(row.text ?? '').toLowerCase();
      if (!check.allOf.every(pattern => text.includes(pattern.toLowerCase()))) return false;
      if (check.maxPriority !== undefined && Number(row.priority ?? 99) > check.maxPriority) return false;
      if (check.minConfidence !== undefined && Number(row.confidence ?? 0) < check.minConfidence) return false;
      return true;
    });
    if (matches.length === 0) failures.push(`memory missing: ${check.description}`);
  }
  return failures;
}

function checkForbiddenMemory(rows, checks) {
  const failures = [];
  for (const check of checks) {
    for (const row of rows) {
      if (check.kind && row.kind !== check.kind) continue;
      if (check.status && (row.status ?? 'active') !== check.status) continue;
      const text = String(row.text ?? '').toLowerCase();
      const pattern = check.pattern.toLowerCase();
      const unless = check.unless?.toLowerCase();
      if (text.includes(pattern) && !(unless && text.includes(unless))) {
        failures.push(`forbidden memory still active: ${check.description}: ${row.text}`);
      }
    }
  }
  return failures;
}

function printStep(result) {
  process.stdout.write(`${result.passed ? 'PASS' : 'FAIL'} ${result.name}\n`);
  if (!result.passed) {
    for (const failure of result.failures) process.stdout.write(`  - ${failure}\n`);
    process.stdout.write(`  response: ${result.response.trim()}\n`);
  }
}

function writeProfile(root, profile, provider, model) {
  const profileDir = path.join(root, profile);
  fs.mkdirSync(profileDir, { recursive: true });
  fs.writeFileSync(path.join(profileDir, 'PROFILE.md'), '# Memory Eval\n\nYou are a concise assistant participating in a memory evaluation.\n');
  fs.writeFileSync(path.join(profileDir, 'RULES.md'), [
    '# Rules',
    '',
    '- Reply naturally and briefly.',
    '- Use remembered facts only when they are relevant.',
    '- Do not invent unknown personal details.',
    '',
  ].join('\n'));
  fs.writeFileSync(path.join(profileDir, 'CUSTOM.md'), '');
  fs.writeFileSync(path.join(profileDir, 'profile.toml'), `memories = true\nprovider = "${provider}"\nmodel = "${model}"\n`);
  ensureProfileMemoryFiles(profileDir);
}

function buildConfig(options) {
  const providerConfig = {
    type: options.providerType,
  };
  if (options.baseUrl) providerConfig.baseUrl = options.baseUrl.replace(/\/+$/, '');
  else if (options.providerType === 'ollama') providerConfig.baseUrl = 'http://localhost:11434';
  else if (options.provider === 'openai') providerConfig.baseUrl = 'https://api.openai.com';
  if (options.apiKeyEnv) providerConfig.apiKeyEnv = options.apiKeyEnv;
  if (options.apiKey) providerConfig.apiKey = options.apiKey;

  return {
    default: {
      provider: options.provider,
      model: options.model,
      profile: options.profile,
      timeoutSeconds: options.timeoutSeconds,
      maxOutputTokens: options.maxOutputTokens,
      maxSystemChars: options.maxSystemChars,
      think: options.think,
    },
    models: {
      options: [`${options.provider}/${options.model}`],
    },
    memory: {
      sizeLimit: options.sizeLimit,
      contextLimit: options.contextLimit,
    },
    paths: {
      profilesDir: options.profilesDir,
      sessionsDb: options.sessionsDb,
    },
    providers: {
      [options.provider]: providerConfig,
    },
  };
}

function memoryRows(memoriesDir) {
  const rows = [];
  for (const filename of ['user.jsonl', 'preferences.jsonl', 'auto_short.jsonl']) {
    const filePath = path.join(memoriesDir, filename);
    if (!fs.existsSync(filePath)) continue;
    for (const line of fs.readFileSync(filePath, 'utf-8').split(/\r?\n/)) {
      if (!line.trim()) continue;
      try {
        rows.push({ ...JSON.parse(line), _file: filename });
      } catch {
        rows.push({ _file: filename, malformed: line });
      }
    }
  }
  return rows;
}

function parseArgs(argv) {
  const result = {};
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === '--') continue;
    if (!arg.startsWith('--')) throw new Error(`Unexpected positional argument: ${arg}`);
    const key = toCamel(arg.slice(2));
    if (key === 'keep' || key === 'thinking' || key === 'stopOnFail') {
      result[key] = true;
      continue;
    }
    const value = argv[index + 1];
    if (value === undefined || value.startsWith('--')) throw new Error(`Missing value for ${arg}`);
    result[key] = value;
    index += 1;
  }
  return result;
}

function toCamel(value) {
  return value.replace(/-([a-z])/g, (_, char) => char.toUpperCase());
}

function numberArg(value, fallback) {
  if (value === undefined) return fallback;
  const number = Number(value);
  if (!Number.isFinite(number)) throw new Error(`Expected a number, got ${value}`);
  return number;
}

function expandHome(value) {
  if (value === '~') return os.homedir();
  if (value.startsWith('~/')) return path.join(os.homedir(), value.slice(2));
  return value;
}

function randomSuffix() {
  return Math.random().toString(16).slice(2, 10);
}

function printHelp() {
  process.stdout.write(`Marifold memory eval

Usage:
  pnpm memory-eval -- --provider ollama --model gemma4:e4b --suite professional

Options:
  --provider <name>          Provider key to configure. Default: ollama
  --provider-type <type>     ollama, openai-compatible, or anthropic
  --model <model>            Model name. Default: gemma4:e4b
  --base-url <url>           Provider base URL
  --api-key-env <name>       Environment variable containing provider API key
  --api-key <value>          API key value for the temporary eval config
  --suite <name>             smoke or professional. Default: professional
  --thinking                 Enable thinking mode for the eval run
  --timeout <seconds>        Provider timeout seconds. Default: 120
  --context-limit <chars>    Memory context limit. Default: 2400
  --size-limit <chars>       Short-term memory size limit. Default: 50000
  --json-report <file>       Write JSON result report
  --workdir <dir>            Use an existing or explicit eval workspace
  --keep                     Keep the temporary eval workspace
  --stop-on-fail             Stop after the first failed eval step
`);
}
